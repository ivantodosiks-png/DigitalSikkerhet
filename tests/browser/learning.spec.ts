test('mobile menu traps focus, closes on Escape, and restores focus', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await demo(page)
  const trigger = page.getByRole('button', { name: 'Åpne læringsmeny' })
  await expect(page.getByRole('navigation', { name: 'Læringsmeny' })).not.toBeVisible()
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Læringsmeny' })
  await expect(dialog).toBeVisible()
  for (let i = 0; i < 10; i++) {
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate(element => element.contains(document.activeElement))).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
})

