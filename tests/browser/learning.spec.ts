test('all modules, real passing scores, achievements, and repeat XP protection', async ({ page }) => {
  await demo(page)
  for (const id of ['passord', 'phishing', 'personvern'] as const) {
    for (let lesson = 0; lesson < 3; lesson++) {
      await page.goto(`/courses/${id}?lesson=${lesson}`)
      await page.getByRole('button', { name: 'Marker som fullført' }).click()
      await expect(page.getByRole('button', { name: 'Fullført', exact: true })).toBeDisabled()
    }
    await quiz(page, id)
    await expect(page.getByText('Kurset er fullført og kursmerket er låst opp!')).toBeVisible()
  }
  await quiz(page, 'passord')
  await page.goto('/dashboard')
  await expect(page.locator('.stat-card').filter({ hasText: 'Opptjente XP' }).locator('strong')).toHaveText('570')
  await expect(page.locator('.stat-card').filter({ hasText: 'Kurs fullført' }).locator('strong')).toHaveText('3 / 3')
  await expect(page.locator('.progress-ring strong')).toHaveText('100%')
  await page.goto('/profile')
  await expect(page.locator('.achievement.unlocked')).toHaveCount(5)
  await page.reload()
  await expect(page.locator('.achievement.unlocked')).toHaveCount(5)
})
