import { test, expect, type Page } from '@playwright/test'
import { questions } from '../../src/data/questions'
import type { CourseId } from '../../src/types'

const key = 'digital-sikkerhet:v1'
async function demo(page: Page) {
  await page.goto('/login')
  await page.getByRole('button', { name: 'Prøv med demoprofil' }).click()
  await expect(page.getByRole('heading', { name: 'Hei, Alex' })).toBeVisible()
}
async function stored(page: Page) {
  return page.evaluate(k => JSON.parse(localStorage.getItem(k) ?? 'null'), key)
}
async function quiz(page: Page, id: CourseId, correct = true) {
  await page.goto(`/courses/${id}/quiz`)
  for (let i = 0; i < questions[id].length; i++) {
    const q = questions[id][i]
    await expect(page.getByRole('button', { name: 'Sjekk svaret' })).toBeDisabled()
    await page.getByRole('radio').nth(correct ? q.correct : (q.correct + 1) % q.options.length).click()
    await page.getByRole('button', { name: 'Sjekk svaret' }).click()
    await expect(page.locator('.feedback')).toBeVisible()
    await page.getByRole('button', { name: i === questions[id].length - 1 ? 'Se resultatet' : 'Neste spørsmål' }).click()
  }
  await expect(page.getByRole('heading', { name: correct ? 'Dette har du kontroll på!' : 'Du er på vei. Prøv igjen!' })).toBeVisible()
}
